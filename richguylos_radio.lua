    ui.textWrapped('This radio was created by RichGuyLos and is locked to his '
      .. 'servers. It will not run anywhere else.')
    ui.separator()
    -- Shown so an authorised server that fails to match can be identified and
    -- added to the build. It leaks nothing: this is the public address anyone
    -- already types in to connect.
    ui.textColored('Either this server is not authorised, or this build has '
      .. 'passed its expiry date and a new one is needed from the author.',
      rgbm(0.46, 0.58, 0.72, 1))
    ui.separator()
    -- Shown so an authorised server that fails to match can be identified and
    -- added to the build. It leaks nothing: this is the public address anyone
    -- already types in to connect.
    ui.textColored('This server reports:', rgbm(0.46, 0.58, 0.72, 1))
    for _, ident in ipairs(serverIdents()) do
      ui.text('  ' .. ident)
    end
    ui.text('  date ' .. os.date('%Y-%m-%d'))
    return false
  end

  local station = currentStation()
  ui.text(status .. '  //  ' .. station.frequency)
  ui.textWrapped(statusDetail)
  ui.separator()

  for i, item in ipairs(stations) do
    if ui.selectable(item.frequency .. '  //  ' .. item.name, selected == i) then
      passes = 0
      tune(i, 1)
    end
  end

  ui.separator()
  ui.text('AUDIO OUTPUT // CSP NATIVE')
  local nextVolume = ui.slider('##rglRadioVolume', volume * 100, 0, 100, '%.0f%%') / 100
  if math.abs(nextVolume - volume) > 0.001 then
    volume = nextVolume
    applyVolume()
  end

  if ui.button(powered and 'POWER OFF' or 'POWER ON', vec2(105, 32)) then
    togglePower()
  end
  ui.sameLine()
  if ui.button(muted and 'UNMUTE' or 'MUTE', vec2(90, 32)) then
    muted = not muted
    applyVolume()
  end
  ui.sameLine()
  if ui.button('RECONNECT', vec2(105, 32)) then
    passes = 0
    tune(selected, 1)
  end

  ui.textColored('Voice chat: CSP Mumble // positional PTT', rgbm(0.28, 1.00, 0.58, 1))
  return false
end

